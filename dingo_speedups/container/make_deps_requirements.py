#!/usr/bin/env python3
"""Pinned pip requirements for the dependencies-only image: The CPU image's pins without DINGO.

Starts from the same recorded dingo_env package list and the same rules as the
DINGO-Lensing image (../../parallelisation/container/make_requirements.py, used
unchanged), then also leaves out dingo-gw. So the image has every package at the
version our earlier tests ran, and no DINGO except the one a job ships
(../pack_dingo.py, checked by ../guard.py).

Standard library only.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Dict, List

HERE = Path(__file__).resolve().parent
PARALLELISATION_CONTAINER = HERE.parents[1] / "parallelisation" / "container"
sys.path.insert(0, str(PARALLELISATION_CONTAINER))

from make_requirements import make_requirements, read_pip_list  # noqa: E402

PIP_LIST = PARALLELISATION_CONTAINER / "dingo_env_pip_list.txt"
REQUIREMENTS = HERE / "requirements-deps-cpu.txt"
EXCLUDED = ("dingo-gw",)
HEADER = (
    "# Generated by dingo_speedups/container/make_deps_requirements.py from "
    "parallelisation/container/dingo_env_pip_list.txt; do not edit. No dingo-gw: Jobs ship DINGO."
)


def make_deps_requirements(packages: Dict[str, str]) -> List[str]:
    """The CPU image's requirement lines, with a new header and without EXCLUDED."""
    missing = [name for name in EXCLUDED if name not in packages]
    if missing:
        raise ValueError(f"Expected to exclude {missing}, but the package list does not have them")
    lines = make_requirements(packages)
    kept = [line for line in lines[1:] if line.split("==", 1)[0] not in EXCLUDED]
    return [HEADER, *kept]


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pip-list", type=Path, default=PIP_LIST, help="Recorded dingo_env package list")
    output = parser.add_mutually_exclusive_group(required=True)
    output.add_argument("--output", type=Path, help="Write the requirements here.")
    output.add_argument("--check", type=Path, help="Exit with an error unless this file is up to date.")
    args = parser.parse_args(argv)

    text = "\n".join(make_deps_requirements(read_pip_list(args.pip_list))) + "\n"
    if args.output is not None:
        with open(args.output, "w", newline="\n") as handle:
            handle.write(text)
    elif args.check.read_text().splitlines() != text.splitlines():
        sys.exit(f"{args.check} is out of date: Rerun make_deps_requirements.py --output")


if __name__ == "__main__":
    main()
